#: Fast lookup: code -> name.
COUNTRY_NAMES: dict[str, str] = dict(COUNTRIES)

#: The default market country everywhere a selector appears.
DEFAULT_COUNTRY = "ca"


def is_valid_country(code: str | None) -> bool:
    """True for a real ISO 3166-1 alpha-2 code (lowercase)."""
    return isinstance(code, str) and code in COUNTRY_NAMES


def normalize_country(raw: object, default: str = DEFAULT_COUNTRY) -> str:
    """Lowercase + strip a raw country value; empty means the default.
    Raises ValueError for anything that is not a real ISO code."""
    code = str(raw or "").strip().lower() or default
    if not is_valid_country(code):
        raise ValueError(
            f"{code!r} is not a valid country code — pick a country "
            "from the list")
    return code


def country_options(selected: str = DEFAULT_COUNTRY) -> str:
    """<option> tags for the full list, with `selected` marked.
    Values are the codes; labels are "Name (code)" so the list is
    searchable by name or code in the browser."""
    out = []
    for code, name in COUNTRIES:
        sel = " selected" if code == selected else ""
        out.append(f"<option value='{code}'{sel}>{name} ({code})</option>")
    return "".join(out)
