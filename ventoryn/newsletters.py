"""Email newsletters: drafted from the site's own pages, approved by
the owner, sent through Resend.

Life of a newsletter:

1. **Draft** — composed by hand on the site page, or generated by
   the agent (``draft_newsletter``, same shape as
   ``campaigns.draft_posts``) from the website's own pages and their
   titles: subject, intro, one section per page, each linking to a
   real page of the site. Nothing is sent. The draft waits with its
   tenant-supplied From address and recipient list.
2. **Approved** — the owner approves it with a fresh 2FA code. The
   approval is recorded on the draft (status ``approved``,
   decided_by, decided_at) — that record is what the send step
   requires.
3. **Sent** — ``send_newsletter`` sends it through the Resend
   adapter, and only when the draft carries that approval record.
   A send that cannot go out is recorded as a failed send attempt
   with the reason, never retried in a loop and never faked as sent.

The agent never invents facts: it may only use the site's page
titles and URLs. Every generated newsletter is checked: subject
length, section links only to the site's own pages.
Recipients are only ever the addresses the tenant supplied — never
harvested, never guessed. When Resend is not configured (no operator
key yet) the send step refuses honestly and the UI says so plainly.
"""

from __future__ import annotations

import html
import json
import re
from urllib.parse import urlparse

from ventoryn.resend_email import MAX_RECIPIENTS, send_email
from ventoryn.saas import SaasError

MAX_SECTIONS = 8
SUBJECT_MAX_CHARS = 200
INTRO_MAX_CHARS = 2000
SECTION_TEXT_MAX_CHARS = 2000

_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")


def _clean(text: str) -> str:
    return re.sub(r"\s+", " ", str(text or "")).strip()


# ---------------------------------------------------------------------------
# Tenant-supplied addresses — validated, never invented.
# ---------------------------------------------------------------------------

def validate_recipients(raw: str) -> list[str]:
    """The tenant-supplied recipient list: one email per line or
    comma-separated. Returns the deduplicated list, or raises
    ValueError with plain words. Never invents an address."""
    seen: set[str] = set()
    out: list[str] = []
    for part in re.split(r"[,\n]", raw or ""):
        addr = part.strip()
        if not addr:
            continue
        if not _EMAIL_RE.match(addr):
            raise ValueError(
                f"'{addr}' is not an email address — fix it or remove it.")
        key = addr.lower()
        if key in seen:
            continue
        seen.add(key)
        out.append(addr)
    if not out:
        raise ValueError("Add at least one recipient email address.")
    if len(out) > MAX_RECIPIENTS:
        raise ValueError(
            f"Too many recipients ({len(out)}) — one newsletter covers "
            f"at most {MAX_RECIPIENTS}.")
    return out


def validate_from_email(raw: str) -> str:
    """The tenant-supplied From address. It must be on a domain
    verified in Resend or Resend refuses the send."""
    addr = (raw or "").strip()
    if not _EMAIL_RE.match(addr):
        raise ValueError(
            "Enter a From email address, e.g. news@yoursite.com — it "
            "must be on a domain verified in Resend.")
    return addr


# ---------------------------------------------------------------------------
# Generation — mirrors campaigns.draft_posts.
# ---------------------------------------------------------------------------

def validate_newsletter(raw: dict, *, allowed_urls: set[str],
                        fallback_url: str) -> dict | None:
    """Keep only a usable generated newsletter: a subject that fits,
    an intro, sections with real text, links only to the site's own
    pages (anything else becomes the home page). Returns None when
    nothing usable remains."""
    if not isinstance(raw, dict):
        return None
    subject = _clean(raw.get("subject"))[:SUBJECT_MAX_CHARS]
    intro = _clean(raw.get("intro"))[:INTRO_MAX_CHARS]
    if not subject or not intro:
        return None
    sections: list[dict] = []
    for item in (raw.get("sections") or [])[:MAX_SECTIONS]:
        if not isinstance(item, dict):
            continue
        heading = _clean(item.get("heading"))
        text = _clean(item.get("text"))[:SECTION_TEXT_MAX_CHARS]
        if not heading or not text:
            continue
        link = str(item.get("link") or "").strip()
        if link not in allowed_urls:
            link = fallback_url
        sections.append({"heading": heading, "text": text, "link": link})
    if not sections:
        return None
    return {"subject": subject, "intro": intro, "sections": sections}


def draft_newsletter(site: dict, *, llm=None, inventory=None) -> dict:
    """Ask the AI for a newsletter draft. Raises RuntimeError when it
    cannot produce a usable draft."""
    from agents.marketing.agent import clean_llm_text
    from core.llm import LLMGateway
    from core.seo_content import fetch_inventory

    if inventory is None:
        try:
            inventory = fetch_inventory(site["url"], max_pages=25)
        except ValueError:
            inventory = None
    pages = [(p.url, getattr(p, "title", "") or "") for p in
             (inventory.pages if inventory else [])][:25]
    allowed = {u for u, _ in pages} | {site["url"]}
    page_list = "\n".join(f"- {u}  ({t})" for u, t in pages) or f"- {site['url']}"
    prompt = (
        f"You write an email newsletter for the website {site['url']} "
        f"(market: {site.get('country', '')}, language: {site.get('language', 'en')}).\n"
        f"Write ONE newsletter: a subject line, a short intro, and one "
        f"section per page below (at most {MAX_SECTIONS} sections).\n\n"
        f"The ONLY facts you may use are these pages and their titles — never "
        f"invent prices, numbers, features, testimonials or claims:\n{page_list}\n\n"
        f"Rules: written in the site's language, helpful and specific, "
        f"no URLs in the text itself — pick for each section the most "
        f"relevant page above as its link.\n"
        'Return ONLY JSON: {"subject": "...", "intro": "...", '
        '"sections": [{"heading": "...", "text": "...", '
        '"link": "<one page URL above>"}]}')
    gateway = llm or LLMGateway()
    result = gateway.complete(prompt, tier=getattr(LLMGateway, "SMART", "smart"),
                              system="You are a careful newsletter writer. JSON only.",
                              json_mode=True, timeout=180)
    payload = clean_llm_text(result.get("json") or {})
    newsletter = validate_newsletter(
        payload or {}, allowed_urls=allowed, fallback_url=site["url"])
    if not newsletter:
        raise RuntimeError("the agent returned no usable newsletter")
    return newsletter


# ---------------------------------------------------------------------------
# Rendering a stored draft into the email itself.
# ---------------------------------------------------------------------------

def newsletter_body_text(newsletter: dict) -> str:
    """Plain-text body: intro, then one section per stored section."""
    sections = newsletter.get("sections") or []
    if isinstance(sections, str):
        try:
            sections = json.loads(sections)
        except ValueError:
            sections = []
    parts = [newsletter.get("body_text") or ""]
    for s in sections:
        if not isinstance(s, dict):
            continue
        parts.append(f"\n{s.get('heading', '')}\n{s.get('text', '')}")
        if s.get("link"):
            parts.append(s["link"])
    return "\n".join(p for p in parts if p).strip()


def newsletter_body_html(newsletter: dict) -> str:
    """HTML body: the same content, escaped, as simple headings and
    paragraphs. No tracking pixels, no scripts."""
    esc = html.escape
    sections = newsletter.get("sections") or []
    if isinstance(sections, str):
        try:
            sections = json.loads(sections)
        except ValueError:
            sections = []
    intro = esc(newsletter.get("body_text") or "")
    rows = "".join(
        f"<h2>{esc(s.get('heading', ''))}</h2>"
        f"<p>{esc(s.get('text', ''))}</p>"
        + (f"<p><a href=\"{esc(s['link'], quote=True)}\">"
           f"{esc(s['link'])}</a></p>" if s.get("link") else "")
        for s in sections if isinstance(s, dict))
    return f"<p>{intro}</p>{rows}" if (intro or rows) else ""


# ---------------------------------------------------------------------------
# Approval + send — the draft-only guarantee lives here.
# ---------------------------------------------------------------------------

def approve_newsletter(store, newsletter_id: str, decided_by: str) -> bool:
    """Record the human approval: draft → approved. Only a still-draft
    newsletter can be approved — an already-decided one returns
    False and is left untouched."""
    return store.decide_newsletter(newsletter_id, "approved",
                                   decided_by=decided_by)


def send_newsletter(store, config, account: dict, site_id: str,
                    newsletter_id: str, client=None) -> tuple[bool, str]:
    """Send one APPROVED newsletter. The ONLY path that ever calls
    Resend — creating or generating a draft never sends it, and a
    draft without an approval record is never sent.

    Enforces, in order: posting not paused for the account; the
    newsletter belongs to this site; status is ``approved`` (a mere
    draft, rejected, already-sent, or failed newsletter is refused
    WITHOUT touching the transport); Resend configured. A provider
    failure is recorded as a failed send attempt with the reason.
    Returns (sent, message)."""
    if account.get("posting_paused"):
        return False, "Posting is paused for this account."
    newsletter = store.get_newsletter(newsletter_id)
    if newsletter is None or newsletter["site_id"] != site_id:
        return False, "Newsletter not found."
    if newsletter["status"] != "approved":
        if newsletter["status"] == "draft":
            return False, ("This newsletter is still a draft — approve "
                           "it first. Nothing was sent.")
        return False, (f"This newsletter was already "
                       f"{newsletter['status']}. Nothing was sent.")
    if not config.resend_configured:
        return False, ("Email sending is not set up yet — the Resend "
                       "API key is not configured. Nothing was sent.")
    recipients = newsletter.get("recipients") or []
    if isinstance(recipients, str):
        try:
            recipients = json.loads(recipients)
        except ValueError:
            recipients = []
    try:
        result = send_email(
            config.resend_api_key,
            from_email=newsletter.get("from_email") or "",
            to=recipients,
            subject=newsletter.get("subject") or "",
            html=newsletter_body_html(newsletter) or None,
            text=newsletter_body_text(newsletter) or None,
            client=client)
    except SaasError as exc:
        store.record_newsletter_send(
            newsletter_id, site_id, "failed",
            recipient_count=len(recipients), error=str(exc))
        store.decide_newsletter(newsletter_id, "send_failed",
                                decided_by=newsletter.get("decided_by") or "")
        return False, str(exc)
    resend_id = result.get("id") or ""
    store.record_newsletter_send(
        newsletter_id, site_id, "sent", resend_id=resend_id,
        recipient_count=len(recipients))
    store.mark_newsletter_sent(newsletter_id, resend_id)
    return True, (f"Sent to {len(recipients)} recipient(s)"
                  + (f" (Resend id {resend_id})." if resend_id else "."))


# ---------------------------------------------------------------------------
# Site-page section — same card framing as the social draft sections.
# ---------------------------------------------------------------------------

def _esc(v) -> str:
    return html.escape(str(v), quote=True)


def newsletter_section_html(store, config, account: dict, site: dict,
                            totp_field: str = "") -> str:
    """The Email newsletters section for the site-detail page."""
    site_id = site["id"]
    newsletters = store.list_newsletters(site_id)
    configured = config.resend_configured
    status_line = (
        "<p class='muted'>Email sending is ready — newsletters send "
        "through Resend once you approve them.</p>" if configured else
        "<p class='muted'>Email sending is not set up yet — the "
        "operator still needs to add the Resend API key "
        "(VENTORYN_RESEND_API_KEY) and restart. You can still draft "
        "newsletters; nothing can send until then.</p>")
    rows = ""
    for n in newsletters:
        recipients = n.get("recipients") or []
        if isinstance(recipients, str):
            try:
                recipients = json.loads(recipients)
            except ValueError:
                recipients = []
        body = (n.get("body_text") or "")[:400]
        rows += (
            f"<div class='card'><h4>{_esc(n.get('subject') or '(no subject)')}</h4>"
            f"<p class='muted'>From {_esc(n.get('from_email') or '—')} — "
            f"to {len(recipients)} recipient(s)</p>"
            f"<p>{_esc(body)}</p>"
            f"<p>Status: <strong>{_esc(n.get('status') or '')}</strong>"
            + (f" (Resend {_esc(n['resend_id'])})"
               if n.get("resend_id") else "")
            + (f" — {_esc(n['decided_by'])}" if n.get("decided_by") else "")
            + "</p>"
            + (f"<form method='post' action='/websites/sites/{_esc(site_id)}"
               f"/newsletters/{_esc(n['id'])}/approve'>{totp_field}<p>"
               "<button class='btn btn-primary' type='submit'>"
               + ("Approve &amp; send" if n.get("status") == "draft"
                  else "Retry send" if n.get("status") == "send_failed"
                  else "Send now")
               + "</button> "
               "<button class='btn' type='submit' "
               f"formaction='/websites/sites/{_esc(site_id)}/newsletters/"
               f"{_esc(n['id'])}/reject'>Reject</button></p></form>"
               if n.get("status") in ("draft", "approved", "send_failed") else "")
            + "</div>")
    rows = rows or "<p class='muted'>No newsletters yet.</p>"
    return (
        "<div class='card'><h3>Email newsletters</h3>"
        f"{status_line}"
        "<form method='post' action='/websites/sites/"
        f"{_esc(site_id)}/newsletters'>"
        "<label for='nl_subject'>Subject</label>"
        "<input type='text' id='nl_subject' name='subject' maxlength='200'>"
        "<label for='nl_body'>Newsletter text</label>"
        "<textarea id='nl_body' name='body_text' maxlength='2000'></textarea>"
        "<label for='nl_from'>From (must be on a domain verified in Resend)</label>"
        "<input type='email' id='nl_from' name='from_email' required "
        "placeholder='news@yoursite.com'>"
        "<label for='nl_recipients'>Recipients — one email per line (only these "
        "addresses ever receive it)</label>"
        "<textarea id='nl_recipients' name='recipients' required "
        "placeholder='reader@example.com'></textarea>"
        "<p><button class='btn' type='submit'>Save draft</button> "
        "<button class='btn' type='submit' "
        f"formaction='/websites/sites/{_esc(site_id)}/newsletters/generate'>"
        "Generate from website</button></p></form>"
        "<p class='muted'>Nothing is sent until you click Approve &amp; "
        "send on a draft — and sending needs the Resend key set up first.</p>"
        f"<h4>Newsletters</h4>{rows}</div>")
